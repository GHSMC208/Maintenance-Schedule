export function createInitialTransferBagItems(today: string): InventoryItem[] {
  return OFFICIAL_EMERGENCY_BAG_ITEMS.map((entry) => ({
    id: `tb-${String(entry.no).padStart(2, '0')}`,
    categoryId: 'transfer-bag',
    name: entry.name,
    unit: 'CCU',
    locationDetail: entry.locationDetail,
    quantity: entry.quantity,
    parLevel: entry.quantity,
    unitOfMeasure: entry.uom,
    batchOrSerial: `SEAL-TB-${String(entry.no).padStart(2, '0')}`,
    expiryDate: entry.expiryDaysOffset !== null ? addDaysIso(today, entry.expiryDaysOffset) : null,
    lastCheckedDate: addDaysIso(today, -8),
    lastCheckedBy: 'RN Nadia Omar',
    notes: entry.notes,
  }));
}

export function createInitialTransferBagMeta(today: string): TransferBagChecklistMeta {
  const [year, monthNum, day] = today.split('-');
  const d = new Date(Number(year), Math.max(0, Number(monthNum) - 1), Number(day));
  const monthName = Number.isNaN(d.getTime())
    ? ''
    : d.toLocaleDateString('en-US', { month: 'long' });
  return {
    wardNumber: '',
    month: monthName,
    year: year || '',
    checkedBy: '',
    date: `${day}/${monthNum}/${year}`,
  };
}
