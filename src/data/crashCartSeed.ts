function buildCartItems(slotMap: Record<string, string[]>): CrashCartItemRow[] {
  return CRASH_CART_TEMPLATE_ROWS.map((tpl) => {
    const defaultLen =
      tpl.cellLayout === 'single'
        ? 1
        : tpl.cellLayout === 'pair'
          ? 2
          : tpl.cellLayout === 'triple'
            ? 3
            : tpl.cellLayout === 'split-2x2'
              ? 4
              : 6;
    const provided = slotMap[tpl.id] || [];
    const slots = Array.from({ length: defaultLen }, (_, i) => provided[i] ?? '');
    return { ...tpl, slots };
  });
}

